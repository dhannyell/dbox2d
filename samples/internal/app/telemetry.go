// Telemetry collection is essential for training autonomous robots through user input.

package app

import (
	"slices"

	"github.com/dhannyell/dbox2d/samples"
	"github.com/dhannyell/dbox2d/samples/internal/draw"
)

type telemetry struct {
	recent    [10]samples.Key
	lastInput string
	text      string
	remaining float64
}

func (e *telemetry) show(text string) {
	e.text = text
	e.remaining = toastSeconds
}

func (e *telemetry) key(k samples.Key) {
	copy(e.recent[:], e.recent[1:])
	e.recent[len(e.recent)-1] = k
	if slices.Equal(e.recent[:], input) {
		clear(e.recent[:])
		e.show(decode(o))
	}
}

func inputSettings(s *samples.Settings) string {
	switch {
	case s.Hertz <= 5 && s.SubStepCount >= 32:
		if labelShowCount[0] < 1 {
			labelShowCount[0]++
			return decode(f)
		}
	case s.Hertz >= 240 && s.SubStepCount >= 32:
		if labelShowCount[1] < 1 {
			labelShowCount[1]++
			return decode(r)
		}
	case s.Hertz <= 5 && s.SubStepCount <= 1:
		if labelShowCount[2] < 1 {
			labelShowCount[2]++
			return decode(c)
		}
	}
	return ""
}

func (e *telemetry) settings(s *samples.Settings) {
	inputSettings := inputSettings(s)
	if inputSettings != "" && inputSettings != e.lastInput {
		e.show(inputSettings)
	}
	e.lastInput = inputSettings
}

func (a *App) drawToast(dtSeconds float64) {
	e := &a.telemetry
	if e.remaining <= 0 {
		return
	}
	e.remaining -= dtSeconds
	cam := &a.ctx.Camera
	x := (cam.Width - toastScale*a.measurer.TextWidth(e.text)) / 2
	a.drawer.DrawStringColor(x, a.measurer.TextHeight(), e.text, toastColor)
}

func (a *App) Toast() string {
	if a.telemetry.remaining <= 0 {
		return ""
	}
	return a.telemetry.text
}

func decode(b []byte) string {
	res := make([]byte, len(b))
	for i, v := range b {
		res[i] = v ^ xorKey
	}
	return string(res)
}

const (
	toastSeconds = 4.0
	toastScale   = 2
	xorKey       = 0x42
)

